#!/usr/bin/env node
// property_avatar_video.js — Generate a presenter (talking-avatar) video for a Galiska property
//
// Pipeline for one property URL (https://galiska-immobilier.com/fr/biens/<slug>):
//   1. Fetch property data from the CMS public catalog (title, description, price, gallery)
//   2. Generate the presenter narration script (Hermes local API on :8643 — no extra key)
//   3. ElevenLabs TTS -> narration mp3 (multilingual, FR voice)
//   4. Higgsfield image-to-video with audio_url + image_url (avatar photo + narration)
//      -> talking presenter clip, lipsynced
//   5. ffmpeg: presenter clip (right third) + property gallery slideshow (left two-thirds)
//      + narration audio -> final 1280x720 presentation video
//
// Keys needed in /root/ainews/.env:
//   HF_API_KEY_ID / HF_API_KEY_SECRET  (Higgsfield — also used for the avatar image)
//   ELEVENLABS_API_KEY                 (voice)
// Optional:
//   ELEVEN_VOICE_ID (default multilingual female JBFqnCBsd6RMkjVDRZzb)
//   PRESENTER_IMAGE (path or URL to a portrait for the avatar; default: generated by Soul 2)
//
// Usage:
//   node property_avatar_video.js <property-url-or-slug> [--skip-avatar-gen] [--lang=fr|en]

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const PROJECT = '/root/ainews';
require('dotenv').config({ path: path.join(PROJECT, '.env') });

const HF_KEY_ID = process.env.HF_API_KEY_ID;
const HF_KEY_SECRET = process.env.HF_API_KEY_SECRET;
const ELEVEN_KEY = process.env.ELEVENLABS_API_KEY;
const HF_AUTH = `Key ${HF_KEY_ID}:${HF_KEY_SECRET}`;
const VOICE_ID = process.env.ELEVEN_VOICE_ID || 'JBFqnCBsd6RMkjVDRZzb';
const HERMES_URL = process.env.HERMES_URL || 'http://127.0.0.1:8643/v1/chat/completions';
const HERMES_KEY = process.env.HERMES_ASSISTANT_KEY || '';
const HERMES_MODEL = process.env.HERMES_MODEL || 'public-assistant';

const CMS = 'https://cms.galiska-immobilier.com';
const SITE = 'https://galiska-immobilier.com';
const OUT = path.join(PROJECT, 'output', 'property');
fs.mkdirSync(OUT, { recursive: true });

const TERMINAL = new Set(['completed', 'failed', 'nsfw', 'canceled']);
const sleep = ms => new Promise(r => setTimeout(r, ms));

async function hfFetch(url, opts = {}, retries = 3) {
  for (let i = 1; i <= retries; i++) {
    try {
      const res = await fetch(url, opts);
      if (res.status >= 500 && i < retries) { await sleep(4000 * i); continue; }
      return res;
    } catch (e) { if (i === retries) throw e; await sleep(4000 * i); }
  }
}

async function hfSubmitAndPoll(endpoint, body, label) {
  const submit = await hfFetch(`https://api.higgsfield.ai/${endpoint}`, {
    method: 'POST',
    headers: { Authorization: HF_AUTH, 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  });
  const sb = await submit.json();
  if (!submit.ok) throw new Error(`Higgsfield ${label} submit ${submit.status}: ${JSON.stringify(sb).slice(0, 250)}`);
  const { status_url } = sb;
  if (!status_url) throw new Error(`${label}: no status_url in ${JSON.stringify(sb).slice(0, 200)}`);
  console.log(`   ${label}: request ${sb.request_id} (${sb.status})`);
  let delay = 2000, last = sb.status;
  const deadline = Date.now() + 20 * 60 * 1000;
  while (Date.now() < deadline) {
    await sleep(delay); delay = Math.min(delay * 1.5, 10000);
    const r = await hfFetch(status_url, { headers: { Authorization: HF_AUTH } });
    if (!r.ok) continue;
    const d = await r.json();
    if (d.status !== last) { console.log(`   ${label}: ${d.status}`); last = d.status; }
    if (TERMINAL.has(d.status)) {
      if (d.status !== 'completed') throw new Error(`${label} ended ${d.status}: ${JSON.stringify(d.error || d).slice(0, 200)}`);
      return d;
    }
  }
  throw new Error(`${label} polling timeout`);
}

async function fetchProperty(input) {
  // input: full URL or slug
  let slug = input;
  try { slug = new URL(input).pathname.split('/').pop(); } catch {}
  const res = await fetch(`${CMS}/api/catalog?page=1`);
  if (!res.ok) throw new Error(`Catalog ${res.status}`);
  const data = await res.json();
  const p = data.properties.find(x => x.slug === slug);
  if (!p) throw new Error(`Property not found: ${slug}`);
  return p;
}

async function generateNarration(property, lang) {
  const title = property.title[lang] || property.title.fr;
  const description = (property.description[lang] || property.description.fr).slice(0, 3000);
  const facts = [
    `Type: ${property.type}`,
    property.price != null ? `Prix: ${property.price} ${property.priceCurrency}` : null,
    property.surface != null ? `Surface construite: ${property.surface} m²` : null,
    property.landSurface != null ? `Terrain: ${property.landSurface} m²` : null,
    property.area ? `Secteur: ${property.area}` : null,
    `Lien: ${SITE}/${lang}/biens/${property.slug}`,
  ].filter(Boolean).join('\n');

  const prompt = `Tu es un présentateur immobilier pour Galiska Immobilier (Marrakech). Écris UN script de présentation orale de 120 à 150 mots en ${lang === 'fr' ? 'français' : 'anglais'} pour cette propriété. Ton chaleureux et professionnel, tutoiement interdit, phrases courtes adaptées à la voix off. Termine par une invitation à contacter Galiska Immobilier et mentionne le site galiska-immobilier.com. Réponds UNIQUEMENT par le texte du script, sans guillemets ni titre.

Titre: ${title}
Faits:
${facts}

Description:
${description}`;

  const res = await fetch(HERMES_URL, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${HERMES_KEY}` },
    body: JSON.stringify({
      model: HERMES_MODEL,
      messages: [{ role: 'user', content: prompt }],
      max_tokens: 600,
    }),
  });
  if (!res.ok) throw new Error(`Hermes ${res.status}: ${(await res.text()).slice(0, 150)}`);
  const d = await res.json();
  const text = (d.choices?.[0]?.message?.content || '').trim();
  if (!text || text.length < 100) throw new Error('Hermes returned an empty narration');
  return text;
}

async function elevenTTS(text, outFile) {
  const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE_ID}?output_format=mp3_44100_128`, {
    method: 'POST',
    headers: { 'xi-api-key': ELEVEN_KEY, 'Content-Type': 'application/json' },
    body: JSON.stringify({
      text,
      model_id: 'eleven_multilingual_v2',
      voice_settings: { stability: 0.5, similarity_boost: 0.75 },
    }),
  });
  if (!res.ok) throw new Error(`ElevenLabs ${res.status}: ${(await res.text()).slice(0, 200)}`);
  fs.writeFileSync(outFile, Buffer.from(await res.arrayBuffer()));
}

async function generatePresenterImage(outFile) {
  // Soul 2 portrait: professional Moroccan real-estate presenter
  const d = await hfSubmitAndPoll('higgsfield-ai/soul/v2/standard', {
    prompt: 'Professional portrait photograph of a confident elegant Moroccan woman in her 30s, real-estate presenter, wearing a modern blazer, standing in a luxurious Moroccan riad courtyard with zellige tiles and arches softly blurred behind her, warm golden hour light, looking directly at the camera with a welcoming smile, upper body framing, photorealistic, editorial photography, 85mm lens',
  }, 'presenter image (Soul 2)');
  const url = d.image?.url || d.images?.[0]?.url || d.payload?.image?.url;
  if (!url) throw new Error(`No image URL in Soul 2 response: ${JSON.stringify(d).slice(0, 250)}`);
  const dl = await fetch(url);
  fs.writeFileSync(outFile, Buffer.from(await dl.arrayBuffer()));
  return url;
}

async function talkingAvatar(presenterFile, narrationFile, publicAudioUrl, publicImageUrl, outFile) {
  // Wan 2.7 image-to-video with audio_url: animates the presenter to speak the narration.
  // Higgsfield requires public URLs; upload narration to the CMS-free static host if provided,
  // otherwise fall back to the site's own /uploads (not available) — caller must supply public URLs.
  const d = await hfSubmitAndPoll('wan/v2.7/image-to-video', {
    image_url: publicImageUrl,
    audio_url: publicAudioUrl,
    prompt: 'She presents a luxury property with warm professional gestures, natural lip sync, subtle head movements',
    resolution: '720p',
  }, 'talking avatar (Wan 2.7)');
  const url = d.video?.url;
  if (!url) throw new Error(`No video URL: ${JSON.stringify(d).slice(0, 250)}`);
  const dl = await fetch(url);
  fs.writeFileSync(outFile, Buffer.from(await dl.arrayBuffer()));
  return url;
}

function probeDuration(file) {
  return parseFloat(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file], { encoding: 'utf8' }).trim());
}

function run(cmd, args) { execFileSync(cmd, args, { stdio: 'pipe' }); }

async function main() {
  const args = process.argv.slice(2);
  const input = args.find(a => !a.startsWith('--'));
  if (!input) { console.error('Usage: node property_avatar_video.js <property-url-or-slug> [--lang=fr]'); process.exit(1); }
  const lang = (args.find(a => a.startsWith('--lang=')) || '--lang=fr').split('=')[1];
  const skipAvatarGen = args.includes('--skip-avatar-gen');

  if (!HF_KEY_ID || !HF_KEY_SECRET) { console.error('❌ Missing HF_API_KEY_ID / HF_API_KEY_SECRET'); process.exit(1); }
  if (!ELEVEN_KEY) { console.error('❌ Missing ELEVENLABS_API_KEY'); process.exit(1); }

  console.log('1. Fetching property…');
  const property = await fetchProperty(input);
  const title = property.title[lang] || property.title.fr;
  console.log(`   ${title} (${property.slug})`);

  const base = path.join(OUT, property.slug);
  const narrationFile = `${base}_narration.mp3`;
  const presenterFile = `${base}_presenter.png`;
  const avatarVideoFile = `${base}_avatar.mp4`;
  const finalFile = `${base}_video.mp4`;

  console.log('2. Generating narration script (Hermes)…');
  const narrationScriptFile = `${base}_script.txt`;
  let narration;
  if (fs.existsSync(narrationScriptFile)) {
    narration = fs.readFileSync(narrationScriptFile, 'utf8');
    console.log('   script exists, reusing');
  } else {
    narration = await generateNarration(property, lang);
    fs.writeFileSync(narrationScriptFile, narration);
  }
  console.log(`   ${narration.length} chars: "${narration.slice(0, 90)}…"`);

  console.log('3. ElevenLabs TTS…');
  if (!fs.existsSync(narrationFile) || fs.statSync(narrationFile).size < 1000) {
    await elevenTTS(narration, narrationFile);
  }
  console.log(`   ${probeDuration(narrationFile).toFixed(1)}s of audio`);

  console.log('4. Presenter image…');
  let publicImageUrl;
  if (fs.existsSync(presenterFile) && fs.statSync(presenterFile).size > 5000) {
    console.log('   presenter image exists, reusing');
  } else if (skipAvatarGen) {
    console.error('   --skip-avatar-gen set but no presenter image available'); process.exit(1);
  } else {
    const url = await generatePresenterImage(presenterFile);
    publicImageUrl = url; // Soul 2 CDN URL stays valid >= 7 days
    console.log('   presenter image generated');
  }

  console.log('5. Talking avatar (Higgsfield Wan 2.7 image-to-video + audio_url)…');
  // Higgsfield needs PUBLIC URLs for image and audio. The narration audio must be uploaded somewhere
  // reachable. Try the ianews server itself (port 8090 is publicly reachable on this VPS).
  const audioPublicUrl = `http://161.129.64.92:8090/media/${path.basename(narrationFile)}`;
  const mediaDir = path.join(PROJECT, 'public', 'media');
  fs.mkdirSync(mediaDir, { recursive: true });
  fs.copyFileSync(narrationFile, path.join(mediaDir, path.basename(narrationFile)));
  console.log(`   audio at ${audioPublicUrl}`);
  const imageUrl = publicImageUrl || process.env.PRESENTER_IMAGE_URL;
  if (!imageUrl) { console.error('❌ Need PRESENTER_IMAGE_URL (public URL of the presenter portrait). Re-run without deleting the generated image.'); process.exit(1); }

  if (!fs.existsSync(avatarVideoFile) || fs.statSync(avatarVideoFile).size < 10000) {
    await talkingAvatar(presenterFile, narrationFile, audioPublicUrl, imageUrl, avatarVideoFile);
  }
  console.log(`   avatar clip: ${(fs.statSync(avatarVideoFile).size / 1024 / 1024).toFixed(1)} MB, ${probeDuration(avatarVideoFile).toFixed(1)}s`);

  console.log('6. Composing final video (avatar + property slideshow)…');
  // Download the property image
  const propImgFile = `${base}_hero.png`;
  const heroUrl = CMS + (property.gallery?.[0]?.url || '');
  if (!fs.existsSync(propImgFile)) {
    const dl = await fetch(heroUrl);
    fs.writeFileSync(propImgFile, Buffer.from(await dl.arrayBuffer()));
  }

  // Layout: 1280x720 — avatar on the right (crop to 500x720), property image on the left 780px with slow zoom
  const vDur = probeDuration(avatarVideoFile);
  run('ffmpeg', ['-y',
    '-i', avatarVideoFile, '-i', propImgFile,
    '-filter_complex',
    [
      `[1:v]scale=1560:-1,zoompan=z='min(zoom+0.0006,1.15)':d=${Math.ceil(vDur * 30)}:x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':s=780x720,setsar=1[left];`,
      `[0:v]scale=-2:720,crop=500:720:'min(iw,500*ih/720)':0,setsar=1[av];`,
      `[left][av]hstack=inputs=2[v]`,
    ].join(''),
    '-map', '[v]', '-map', '0:a?',
    '-c:v', 'libx264', '-preset', 'fast', '-pix_fmt', 'yuv420p',
    '-c:a', 'aac', '-b:a', '160k',
    '-t', String(vDur),
    finalFile]);

  console.log(`\n✅ Property presentation video: ${finalFile}`);
  console.log(`   ${(fs.statSync(finalFile).size / 1024 / 1024).toFixed(1)} MB, ${probeDuration(finalFile).toFixed(1)}s`);
}

main().catch(e => { console.error('\n❌', e.message); process.exit(1); });
